-- ClinAct taxonomy of its own + clinical scenario (Karina, 2026-10-13).
--
-- PHASE 1 of 2 — the REVIEW phase. Everything here is invisible to the code
-- running in production today, because the private review preview shares the
-- production database:
--
--   1. clinact_specialties — ClinAct's OWN specialty list. Seeded from the
--      specialties the ClinAct cases already use, with the SAME ids, plus
--      Saúde Coletiva (same id as the shared row) and Ortopedia / Urologia
--      (new ids, 101 / 102). The shared `specialties` table — Revalida's — is
--      not touched: adding Ortopedia/Urologia there would surface them across
--      Revalida (dashboard, plano, relatório, study plan, landing count…).
--   2. clinact_topics — ClinAct's OWN topic list, seeded with exactly the
--      topics the cases use, SAME ids. New topics start at id 100000.
--   3. clinact_cases.scenario — one main clinical scenario per case.
--   4. clinact_save_case / clinact_case_document carry `scenario`; an import
--      document WITHOUT the key keeps the stored value (like is_free).
--   5. The two FKs clinact_cases → specialties / topics are DROPPED for the
--      review period: the review build writes ClinAct ids (e.g. Ortopedia 101)
--      while production still writes Revalida ids. For every case that exists
--      today the ids are identical, so nothing moves. Phase 2
--      (schema-patch-clinact-taxonomia-publish.sql) reconciles and re-adds both
--      FKs pointing at the ClinAct tables, at publication.
--
-- The 40 published cases are not modified: same specialty_id, same topic_id,
-- same texts. Re-run safe.
--
-- Rollback (review phase): DROP TABLE clinact_topics, clinact_specialties;
--   ALTER TABLE clinact_cases DROP COLUMN scenario; re-add the two FKs to
--   specialties(id) / topics(id) ON DELETE SET NULL; re-run the functions from
--   schema-patch-clinact-free-cases.sql.

BEGIN;

-- ── 1. ClinAct specialties ─────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS clinact_specialties (
  id            smallint GENERATED BY DEFAULT AS IDENTITY (START WITH 200) PRIMARY KEY,
  slug          text NOT NULL UNIQUE,
  name          text NOT NULL,
  display_order smallint NOT NULL DEFAULT 0,
  active        boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);

-- The specialties the cases use today (any status), same id/slug/name;
-- order follows Revalida's, ×10 so new ones fit in between.
INSERT INTO clinact_specialties (id, slug, name, display_order)
SELECT s.id, s.slug, s.name, s.display_order * 10
  FROM specialties s
 WHERE s.id IN (SELECT DISTINCT specialty_id FROM clinact_cases WHERE specialty_id IS NOT NULL)
    OR s.slug = 'saude-coletiva'
ON CONFLICT (id) DO NOTHING;

-- New in ClinAct only, placed after Cirurgia Geral.
INSERT INTO clinact_specialties (id, slug, name, display_order) VALUES
  (101, 'ortopedia', 'Ortopedia', 131),
  (102, 'urologia',  'Urologia',  132)
ON CONFLICT (id) DO NOTHING;

-- ── 2. ClinAct topics ──────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS clinact_topics (
  id            bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100000) PRIMARY KEY,
  specialty_id  smallint NOT NULL REFERENCES clinact_specialties(id) ON DELETE RESTRICT,
  name          text NOT NULL,
  slug          text NOT NULL,
  active        boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (specialty_id, slug)
);

-- Exactly the topics the cases use, same id/name; filed under the case's
-- specialty (verified identical to the topic's own specialty on 2026-10-13).
INSERT INTO clinact_topics (id, specialty_id, name, slug)
SELECT DISTINCT ON (t.id) t.id, c.specialty_id, t.name, COALESCE(NULLIF(t.slug, ''), 'tema-' || t.id)
  FROM clinact_cases c
  JOIN topics t ON t.id = c.topic_id
 WHERE c.specialty_id IS NOT NULL
   AND c.specialty_id IN (SELECT id FROM clinact_specialties)
 ORDER BY t.id
ON CONFLICT (id) DO NOTHING;

-- Service-role only, like every clinact_* table (default grants revoked).
ALTER TABLE clinact_specialties ENABLE ROW LEVEL SECURITY;
ALTER TABLE clinact_topics      ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON clinact_specialties FROM anon, authenticated;
REVOKE ALL ON clinact_topics      FROM anon, authenticated;

-- ── 3. Clinical scenario ───────────────────────────────────────────────────
ALTER TABLE clinact_cases ADD COLUMN IF NOT EXISTS scenario text;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'clinact_cases_scenario_check') THEN
    ALTER TABLE clinact_cases ADD CONSTRAINT clinact_cases_scenario_check CHECK (
      scenario IS NULL OR scenario IN ('atencao_primaria', 'ambulatorio', 'urgencia', 'emergencia', 'hospital', 'maternidade'));
  END IF;
END $$;

-- ── 5. Review period: the case links stop pointing at Revalida's lists ─────
ALTER TABLE clinact_cases DROP CONSTRAINT IF EXISTS clinact_cases_specialty_id_fkey;
ALTER TABLE clinact_cases DROP CONSTRAINT IF EXISTS clinact_cases_topic_id_fkey;

-- ── 4. The document and the one write path carry `scenario` ────────────────
CREATE OR REPLACE FUNCTION clinact_case_document(p_case_id bigint)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT jsonb_build_object(
    'id', c.id, 'slug', c.slug, 'format', c.format, 'title', c.title,
    'specialty_id', c.specialty_id, 'topic_id', c.topic_id,
    'specialty_text', c.specialty_text, 'topic_text', c.topic_text,
    'difficulty', c.difficulty, 'primary_skill', c.primary_skill,
    'est_minutes', c.est_minutes, 'summary', c.summary, 'takeaway', c.takeaway,
    'final_key', c.final_key, 'notes', c.notes, 'status', c.status,
    'revision', c.revision, 'published_at', c.published_at, 'is_free', c.is_free,
    'scenario', c.scenario,
    'steps', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'id', s.id, 'position', s.position, 'kind', s.kind, 'enabled', s.enabled,
        'scene_key', s.scene_key, 'skill', s.skill, 'content', s.content,
        'options', COALESCE((
          SELECT jsonb_agg(jsonb_build_object(
            'id', o.id, 'position', o.position, 'label', o.label, 'is_correct', o.is_correct,
            'quality', o.quality, 'feedback', o.feedback, 'seduction', o.seduction,
            'effect', o.effect, 'next_scene_key', o.next_scene_key) ORDER BY o.position)
          FROM clinact_options o WHERE o.step_id = s.id), '[]'::jsonb)
      ) ORDER BY s.position)
      FROM clinact_steps s WHERE s.case_id = c.id), '[]'::jsonb),
    'clues', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'id', k.id, 'position', k.position, 'label', k.label, 'detail', k.detail,
        'media', k.media, 'category', k.category, 'is_red_herring', k.is_red_herring,
        'red_herring_reason', k.red_herring_reason, 'cluster', k.cluster) ORDER BY k.position)
      FROM clinact_clues k WHERE k.case_id = c.id), '[]'::jsonb)
  )
  FROM clinact_cases c WHERE c.id = p_case_id;
$$;

-- Full replacement of the function from schema-patch-clinact-free-cases.sql
-- (verified identical to production on 2026-10-13); the only changes are the
-- lines marked -- scenario.
CREATE OR REPLACE FUNCTION clinact_save_case(p_case jsonb, p_actor uuid DEFAULT NULL)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_id       bigint;
  v_status   text;
  v_revision integer;
  v_step     jsonb;
  v_opt      jsonb;
  v_clue     jsonb;
  v_step_id  bigint;
BEGIN
  IF p_case->>'id' IS NOT NULL THEN
    SELECT id, status, revision INTO v_id, v_status, v_revision
      FROM clinact_cases WHERE id = (p_case->>'id')::bigint FOR UPDATE;
  END IF;
  IF v_id IS NULL THEN
    SELECT id, status, revision INTO v_id, v_status, v_revision
      FROM clinact_cases WHERE slug = p_case->>'slug' FOR UPDATE;
  END IF;

  IF v_id IS NULL THEN
    INSERT INTO clinact_cases (
      slug, format, title, specialty_id, topic_id, specialty_text, topic_text,
      difficulty, primary_skill, est_minutes, summary, takeaway, final_key, notes,
      is_free, scenario, created_by)                                   -- scenario
    VALUES (
      p_case->>'slug', p_case->>'format', p_case->>'title',
      NULLIF(p_case->>'specialty_id', '')::smallint, NULLIF(p_case->>'topic_id', '')::bigint,
      p_case->>'specialty_text', p_case->>'topic_text',
      COALESCE(p_case->>'difficulty', 'intermediaria'), p_case->>'primary_skill',
      NULLIF(p_case->>'est_minutes', '')::smallint,
      p_case->>'summary', p_case->>'takeaway', p_case->>'final_key', p_case->>'notes',
      COALESCE((p_case->>'is_free')::boolean, false),
      NULLIF(p_case->>'scenario', ''),                                 -- scenario
      p_actor)
    RETURNING id, status, revision INTO v_id, v_status, v_revision;
  ELSE
    IF v_status = 'published' THEN
      v_revision := v_revision + 1;
    END IF;
    UPDATE clinact_cases SET
      slug          = p_case->>'slug',
      format        = p_case->>'format',
      title         = p_case->>'title',
      specialty_id  = NULLIF(p_case->>'specialty_id', '')::smallint,
      topic_id      = NULLIF(p_case->>'topic_id', '')::bigint,
      specialty_text = p_case->>'specialty_text',
      topic_text    = p_case->>'topic_text',
      difficulty    = COALESCE(p_case->>'difficulty', 'intermediaria'),
      primary_skill = p_case->>'primary_skill',
      est_minutes   = NULLIF(p_case->>'est_minutes', '')::smallint,
      summary       = p_case->>'summary',
      takeaway      = p_case->>'takeaway',
      final_key     = p_case->>'final_key',
      notes         = p_case->>'notes',
      -- Editorial flag: an import document without it must not reset it.
      is_free       = COALESCE((p_case->>'is_free')::boolean, is_free),
      -- A document WITHOUT the key (an old file re-imported) keeps the stored
      -- scenario; the key present with null/"" clears it (the admin's "—").
      scenario      = CASE WHEN p_case ? 'scenario' THEN NULLIF(p_case->>'scenario', '') ELSE scenario END, -- scenario
      revision      = v_revision
    WHERE id = v_id;
    DELETE FROM clinact_steps WHERE case_id = v_id;   -- cascades options
    DELETE FROM clinact_clues WHERE case_id = v_id;
  END IF;

  FOR v_step IN SELECT * FROM jsonb_array_elements(COALESCE(p_case->'steps', '[]'::jsonb)) LOOP
    INSERT INTO clinact_steps (case_id, position, kind, enabled, scene_key, skill, content)
    VALUES (
      v_id, (v_step->>'position')::integer, v_step->>'kind',
      COALESCE((v_step->>'enabled')::boolean, true),
      NULLIF(v_step->>'scene_key', ''), NULLIF(v_step->>'skill', ''),
      COALESCE(v_step->'content', '{}'::jsonb))
    RETURNING id INTO v_step_id;

    FOR v_opt IN SELECT * FROM jsonb_array_elements(COALESCE(v_step->'options', '[]'::jsonb)) LOOP
      INSERT INTO clinact_options (step_id, position, label, is_correct, quality, feedback, seduction, effect, next_scene_key)
      VALUES (
        v_step_id, (v_opt->>'position')::integer, v_opt->>'label',
        COALESCE((v_opt->>'is_correct')::boolean, false),
        NULLIF(v_opt->>'quality', ''), v_opt->>'feedback', v_opt->>'seduction',
        COALESCE(v_opt->'effect', '{}'::jsonb), NULLIF(v_opt->>'next_scene_key', ''));
    END LOOP;
  END LOOP;

  FOR v_clue IN SELECT * FROM jsonb_array_elements(COALESCE(p_case->'clues', '[]'::jsonb)) LOOP
    INSERT INTO clinact_clues (case_id, position, label, detail, media, category, is_red_herring, red_herring_reason, cluster)
    VALUES (
      v_id, (v_clue->>'position')::integer, v_clue->>'label', v_clue->>'detail',
      CASE WHEN v_clue ? 'media' AND jsonb_typeof(v_clue->'media') = 'object' THEN v_clue->'media' ELSE NULL END,
      v_clue->>'category', COALESCE((v_clue->>'is_red_herring')::boolean, false),
      v_clue->>'red_herring_reason', NULLIF(v_clue->>'cluster', ''));
  END LOOP;

  IF v_status = 'published' THEN
    INSERT INTO clinact_case_versions (case_id, revision, published_by, snapshot)
    VALUES (v_id, v_revision, p_actor, clinact_case_document(v_id));
  END IF;

  RETURN v_id;
END;
$$;

REVOKE EXECUTE ON FUNCTION clinact_save_case(jsonb, uuid)     FROM anon, authenticated, public;
REVOKE EXECUTE ON FUNCTION clinact_case_document(bigint)      FROM anon, authenticated, public;

COMMIT;
