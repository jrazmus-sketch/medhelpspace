#!/usr/bin/env node
/* eslint-disable no-console */
/**
 * import-revalida-up-fase2.js — SQL for the Revalida Up file(s) Karina attached to her Fase 2 e-mail
 * (2026-11-18: `urologia-revalida-up.md.docx`). Same Word shape and the same rules as
 * import-revalida-up-fase1.js: the FILE NAME picks the live page; the page keeps its id (Meu Plano links,
 * completions, MemoreCards), its address and its specialty; title from the file, text verbatim; UPDATE in
 * place, never delete + reinsert. Only the delivered page(s) are touched.
 *
 * GENERATOR ONLY (never connects to a database):
 *   node scripts/import-revalida-up-fase2.js          → parsed/revalida-up-fase2-import.sql + -rollback.sql
 *   node scripts/run-sql.js parsed/revalida-up-fase2-import.sql        (once per database)
 */
"use strict";

const fs = require("fs");
const path = require("path");
const { convert, fixTitle, sqlStr } = require("./import-revalida-up-v2.js");

const SRC = process.env.REVALIDA_FASE2_SRC || "C:/Users/jrazm/OneDrive/Desktop/Medhelpspace/11-18-2026/email";
// A later delivery of the same phase gets its own tag, so its files and backup tables never collide with an earlier
// one (CREATE TABLE IF NOT EXISTS would otherwise keep the OLD backup): REVALIDA_FASE2_TAG=fase2b → *_bk_fase2b_ru.
const TAG = process.env.REVALIDA_FASE2_TAG || "fase2";
if (!/^[a-z0-9]+$/.test(TAG)) { console.error("REVALIDA_FASE2_TAG: lowercase letters and digits only"); process.exit(1); }
const OUT = path.join(__dirname, "..", "parsed", `revalida-up-${TAG}-import.sql`);
const OUT_RB = path.join(__dirname, "..", "parsed", `revalida-up-${TAG}-rollback.sql`);

const files = fs.readdirSync(SRC).filter((f) => /-revalida-up\.md\.docx$/.test(f) && !f.startsWith("~$")).sort();
if (files.length === 0) { console.error(`no *-revalida-up.md.docx in ${SRC}`); process.exit(1); }
const rows = [];
const problems = [];
for (const f of files) {
  const slug = f.replace(/\.md\.docx$/, "");
  const { fm, html, stats, warnings } = convert(path.join(SRC, f));
  for (const w of warnings) problems.push(`${f}: ${w}`);
  if (!fm) { problems.push(`${f}: no header`); continue; }
  if (fm.view !== "revalida-up" || fm.type !== "plain-content") problems.push(`${f}: view/type = ${fm.view}/${fm.type}`);
  rows.push({ slug, title: fixTitle(fm.title), fileSlug: fm.slug, fileSpec: fm.specialty, html, ...stats });
}
if (problems.length) { console.error("PROBLEMS — nothing written:\n  " + problems.join("\n  ")); process.exit(1); }

const values = rows.map((r, i) => `  (${i + 1}, ${sqlStr(r.slug)}, ${sqlStr(r.title)}, ${sqlStr(r.html)})`).join(",\n");
const list = rows.map((r) => sqlStr(r.slug)).join(", ");

fs.writeFileSync(OUT, `-- revalida-up-${TAG}-import.sql  (GENERATED by scripts/import-revalida-up-fase2.js — do not hand-edit)
--
-- Karina 2026-11-18, Fase 2: ${rows.length} Revalida Up file(s) attached to her e-mail (${rows.map((r) => r.slug).join(", ")}).
-- Existing page(s): title + text replaced in place (same id, address and specialty). Nothing else is touched.
-- run-sql.js wraps the file in one transaction. Backups: *_bk_${TAG}_ru. Rollback: revalida-up-${TAG}-rollback.sql.

CREATE TEMP TABLE np (rn int, slug text PRIMARY KEY, title text, body text) ON COMMIT DROP;
INSERT INTO np (rn, slug, title, body) VALUES
${values};

DO $$
DECLARE bad text;
BEGIN
  SELECT string_agg(np.slug, ', ') INTO bad FROM np
   WHERE (SELECT count(*) FROM pages p WHERE p.slug = np.slug AND p.view = 'revalida-up' AND p.status = 'publish') <> 1
      OR (SELECT count(*) FROM lessons l JOIN pages p ON p.id = l.page_id WHERE p.slug = np.slug) <> 1;
  IF bad IS NOT NULL THEN RAISE EXCEPTION 'Revalida Up page(s) not found, not published or not with exactly one text: % — nothing changed', bad; END IF;
END $$;

-- Backups (full rows, taken once: a re-run keeps the ORIGINAL state).
CREATE TABLE IF NOT EXISTS pages_bk_${TAG}_ru AS SELECT * FROM pages WHERE slug IN (${list});
CREATE TABLE IF NOT EXISTS lessons_bk_${TAG}_ru AS
  SELECT l.* FROM lessons l JOIN pages p ON p.id = l.page_id WHERE p.slug IN (${list});
ALTER TABLE pages_bk_${TAG}_ru ENABLE ROW LEVEL SECURITY;
ALTER TABLE lessons_bk_${TAG}_ru ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON pages_bk_${TAG}_ru, lessons_bk_${TAG}_ru FROM PUBLIC, anon, authenticated;

UPDATE pages p SET title = np.title, updated_at = now()
FROM np WHERE p.slug = np.slug AND p.view = 'revalida-up';

UPDATE lessons l SET title = np.title, body_html = np.body, updated_at = now()
FROM np JOIN pages p ON p.slug = np.slug AND p.view = 'revalida-up'
WHERE l.page_id = p.id;

-- Expect ${rows.length}: delivered page(s) published with exactly the delivered title and text.
SELECT count(*) AS delivered_live
FROM np JOIN pages p ON p.slug = np.slug AND p.view = 'revalida-up' AND p.status = 'publish' AND p.title = np.title
JOIN lessons l ON l.page_id = p.id AND l.body_html = np.body;

SELECT p.id, p.slug, p.title, s.slug AS specialty,
       (SELECT count(*) FROM topic_content c WHERE c.page_id = p.id) AS meu_plano_links
FROM np JOIN pages p ON p.slug = np.slug LEFT JOIN specialties s ON s.id = p.specialty_id ORDER BY np.rn;
`);

fs.writeFileSync(OUT_RB, `-- revalida-up-${TAG}-rollback.sql  (GENERATED) — restores the page(s) exactly as they were before
-- revalida-up-${TAG}-import.sql (timestamps included).
DO $$ BEGIN
  IF to_regclass('public.pages_bk_${TAG}_ru') IS NULL OR to_regclass('public.lessons_bk_${TAG}_ru') IS NULL THEN
    RAISE EXCEPTION 'backup tables *_bk_${TAG}_ru not found — nothing changed';
  END IF;
END $$;
ALTER TABLE pages DISABLE TRIGGER USER;
ALTER TABLE lessons DISABLE TRIGGER USER;
UPDATE pages p SET title = b.title, status = b.status, updated_at = b.updated_at FROM pages_bk_${TAG}_ru b WHERE p.id = b.id;
UPDATE lessons l SET title = b.title, body_html = b.body_html, updated_at = b.updated_at FROM lessons_bk_${TAG}_ru b WHERE l.id = b.id;
ALTER TABLE pages ENABLE TRIGGER USER;
ALTER TABLE lessons ENABLE TRIGGER USER;
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pages p JOIN pages_bk_${TAG}_ru b ON b.id = p.id WHERE row(p.*) IS DISTINCT FROM row(b.*))
     OR EXISTS (SELECT 1 FROM lessons l JOIN lessons_bk_${TAG}_ru b ON b.id = l.id WHERE row(l.*) IS DISTINCT FROM row(b.*)) THEN
    RAISE EXCEPTION 'rollback did not restore every row — nothing changed';
  END IF;
END $$;
DROP TABLE pages_bk_${TAG}_ru, lessons_bk_${TAG}_ru;
`);

console.log(`Revalida Up — Fase 2 (${rows.length} file(s))`);
for (const r of rows) console.log(`  ${r.slug} | título: ${r.title} | arquivo diz: slug=${r.fileSlug} specialty=${r.fileSpec} | ${JSON.stringify(Object.fromEntries(Object.entries(r).filter(([k]) => !["slug", "title", "fileSlug", "fileSpec", "html"].includes(k))))}`);
console.log(`→ ${path.relative(process.cwd(), OUT)}\n→ ${path.relative(process.cwd(), OUT_RB)}`);
