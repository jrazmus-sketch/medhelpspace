#!/usr/bin/env node
/**
 * Measures the real length of every MedVoice audio (ffprobe on the Bunny URL) and writes a re-runnable SQL
 * patch keyed by audio_url (ids can drift between prod and local; the URL does not).
 *
 *   node scripts/measure-audio-durations.js                 # reads the LOCAL database
 *   DB=<postgres url> node scripts/measure-audio-durations.js
 *
 * Output: schema-patch-medvoice-audio-durations.sql → apply with run-sql.js to prod AND local.
 * Only fills lessons.audio_duration_seconds; never touches text or audio_url. Needs ffprobe on PATH.
 * Meu Plano uses the measured length as the MedVoice time estimate (Karina 2026-11-17); a lesson without a
 * measurement falls back to study_plan_settings.medvoice_fallback_minutes.
 */
const fs = require("fs");
const path = require("path");
const { execFile } = require("child_process");
const postgres = require("postgres");

const root = path.join(__dirname, "..");
const url = process.env.DB || "postgresql://postgres:postgres@127.0.0.1:55322/postgres";
const sql = postgres(url, { max: 1, ssl: /127\.0\.0\.1|localhost/.test(url) ? false : "require" });

function probe(audioUrl) {
  return new Promise((resolve) => {
    execFile(
      "ffprobe",
      ["-v", "error", "-show_entries", "format=duration", "-of", "default=noprint_wrappers=1:nokey=1", audioUrl],
      { timeout: 60000 },
      (err, stdout) => {
        const s = parseFloat(String(stdout).trim());
        resolve(err || !Number.isFinite(s) || s <= 0 ? null : Math.round(s));
      },
    );
  });
}

(async () => {
  const rows = await sql`
    select l.id, l.title, l.audio_url
      from lessons l join pages p on p.id = l.page_id
     where p.track_id = 1 and l.audio_url is not null
     order by l.id`;
  await sql.end();

  const out = [];
  const failed = [];
  const CONCURRENCY = 6;
  let next = 0;
  async function worker() {
    while (next < rows.length) {
      const r = rows[next++];
      // The stored URL as-is first (it may already carry %-escapes); re-encoded only if that fails.
      const secs = (await probe(r.audio_url)) ?? (await probe(encodeURI(r.audio_url)));
      if (secs == null) failed.push(r);
      else out.push({ ...r, secs });
    }
  }
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));
  out.sort((a, b) => a.id - b.id);

  const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
  const lines = [
    "-- schema-patch-medvoice-audio-durations.sql — GENERATED by scripts/measure-audio-durations.js",
    `-- ${out.length} MedVoice audios measured with ffprobe; ${failed.length} could not be read (left NULL → settings fallback).`,
    "-- Keyed by audio_url. Only fills lessons.audio_duration_seconds. Re-run safe.",
    "BEGIN;",
    ...out.map((r) => `UPDATE lessons SET audio_duration_seconds = ${r.secs} WHERE audio_url = ${q(r.audio_url)}; -- ${r.title}`),
    ...failed.map((r) => `-- NOT MEASURED: ${r.title} (${r.audio_url})`),
    "COMMIT;",
    "",
  ];
  fs.writeFileSync(path.join(root, "schema-patch-medvoice-audio-durations.sql"), lines.join("\n"));
  const total = out.reduce((s, r) => s + r.secs, 0);
  console.log(`measured ${out.length}/${rows.length}; failed ${failed.length}; total ${(total / 3600).toFixed(1)} h; avg ${(total / out.length / 60).toFixed(1)} min`);
  for (const r of failed) console.log("  FAILED:", r.title, r.audio_url);
})().catch((e) => { console.error(e); process.exit(1); });
