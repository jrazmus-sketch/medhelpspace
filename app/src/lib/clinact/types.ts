/** Runtime state folded into `clinact_attempts.state` (§2.4). */
export type AttemptState = {
  /** Index into the enabled step list of the next step to show. */
  cursor: number;
  /** step_id → what was answered. */
  answered: Record<string, AnsweredStep>;
  /** Prontuário Vivo drawers, folded from chosen effects. */
  revealed: Reveal[];
  estado: Record<string, string>;
  relogio: number;
  scene_key?: string | null;
};

export type AnsweredStep = {
  option_id?: number | null;
  order?: number[];
  /** Investigation: every option the student ordered, by id. */
  selected?: number[];
  is_correct: boolean;
  weight: number;
  confidence?: Confidence | null;
  time_ms?: number | null;
};

