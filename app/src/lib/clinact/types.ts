/**
 * ClinAct — shared types for the case engine.
 *
 * The `CaseDoc` shape is THE document: the editor edits it, the importer
 * produces it, `clinact_save_case` persists it, `clinact_case_document`
 * returns it, and `clinact_case_versions.snapshot` freezes it. One shape,
 * every direction, so nothing can drift between the panel and the DB.
 *
 * Pure types + constants only — safe to import from client components.
 */

