/**
 * The ClinAct subscription flow: plan → subscriber (card encrypted in the
 * browser) → subscription → access.
 *
 * TWO RULES GOVERN EVERYTHING HERE, both learned in sandbox and both costing
 * real money if broken:
 *
 * 1. ACCESS FOLLOWS THE PAID INVOICE. POST /subscriptions answers 201 even when
 *    the card was declined — the subscription is simply born OVERDUE. And after
 *    a recovered charge the invoice reads PAID minutes before the subscription
 *    turns ACTIVE. So the invoice, not the status, decides.
 *
 * 2. A RETRY NEVER GETS A NEW IDEMPOTENCY KEY. PagBank does not deduplicate on
 *    reference_id: the same request twice creates a second subscription and
 *    charges it again. Every attempt carries one key, derived from the attempt
 *    id the browser generated; a replay answers 409 and we reconcile instead.
 *
 * The CVV passes through this module once, as an argument, on its way to
 * PagBank. It is never stored, never logged (the audit sink strips it by key),
 * and never attached to an error.
 */

/**
 * Refuses the one combination that would hand out real access for a test card:
 * the LIVE site talking to the PagBank SANDBOX. Vercel already holds the
 * sandbox token, so without this a logged-in visitor who found the URL could
 * "pay" with 5555666677778884 and be granted a subscription.
 *
 * Production hosting must be pointed at production PagBank, or the checkout
 * stays shut.
 */
export function subscriptionsUnavailable(): boolean {
  return process.env.VERCEL_ENV === "production" && getSubscriptionsEnv() !== "production";
}

export type SubscribeInput = {
  userId: string;
  email: string;
  /** Name as printed on the card. */
  name: string;
  /** CPF, digits only. */
  taxId: string;
  planKey: ClinactPlanKey;
  encryptedCard: string;
  securityCode: string;
  /**
   * One id per checkout attempt, generated by the browser and kept across
   * retries of THAT attempt. It becomes the reference_id and the idempotency
   * keys, which is what makes a resubmit safe.
   */
  attemptId: string;
  /** REQUIRED by PagBank: POST /customers refuses a subscriber without phones. */
  phone: { area: string; number: string };
  /**
   * "Dados para a nota fiscal" — who the NFS-e is issued to, chosen at checkout
   * (Karina 2026-10-27). Validated by the route. Never sent to PagBank and never
   * derived from the card: the cardholder above is payment data only.
   */
  tomador: NfseTomador;
  /**
   * The first charge the checkout SHOWED, in cents. When it no longer matches
   * what would be charged now (the promotion ended while the page was open),
   * nothing is charged and the student is told the new price.
   */
  expectedFirstCents?: number;
};

export type SubscribeResult =
  | { ok: true; state: "paid"; subscriptionId: string; paidUntil: string }
  | { ok: true; state: "pending"; subscriptionId: string }
  | { ok: false; error: string; priceChanged?: boolean };

/** pt-BR, and never leaks PagBank's wording to the student. */
const GENERIC_ERROR =
  "Não foi possível concluir a assinatura. Nenhuma cobrança foi feita. Tente novamente em alguns instantes.";
const DECLINED_ERROR =
  "O pagamento não foi aprovado pelo emissor do cartão. Confira os dados ou use outro cartão — nenhum valor foi cobrado.";
const DUPLICATE_CUSTOMER_ERROR =
  "Já existe um cadastro no PagBank com este CPF. Fale com o suporte para vincular a sua assinatura.";

/**
 * The subscriber reference we send to PagBank. Deliberately user-scoped: it is
 * the only thing that lets us prove later that a customer found by CPF is
 * really this user's. See resolveCustomer.
 */
function customerReference(userId: string): string {
  return `clinact-user-${userId}`;
}

/** Alphanumeric only, PagBank's rule for the idempotency key. */
function key(...parts: string[]): string {
  return parts.join("").replace(/[^a-zA-Z0-9]/g, "").slice(0, 200);
}

/**
 * Records every PagBank call. Deliberately tolerant: a failed audit write must
 * never cost a student their subscription, so the sink swallows its own errors
 * (the client also wraps it).
 */
function auditSink(userId: string, referenceId: string) {
  const env = getSubscriptionsEnv();
  return async (entry: PagBankAuditEntry) => {
    const admin = createAdminClient();
    await admin.from("pagbank_subscription_api_calls").insert({
      user_id: userId,
      reference_id: referenceId,
      environment: env,
      method: entry.method,
      path: entry.path,
      status: entry.status,
      request: entry.request as Record<string, unknown> | null,
      response: entry.response as Record<string, unknown> | null,
    });
  };
}

/**
 * The PagBank plan id for a ClinAct plan, created on first use.
 *
 * Plans are per-environment and per-credential, so production starts empty:
 * the first subscriber creates them.
 *
 * THE PRICE IS PART OF THE REFERENCE (`clinact-mensal-2990`), and the amount is
 * checked again after the lookup. Matching on `clinact-mensal` alone would mean
 * that changing the price in plans.ts keeps charging whatever the old PagBank
 * plan says — the exact drift Karina's decision 2 exists to prevent, and it
 * would be invisible: the page would show the new price and the card would be
 * charged the old one. A changed price can now only ever create a new plan.
 */
async function ensurePlanId(planKey: ClinactPlanKey, audit: ReturnType<typeof auditSink>): Promise<string> {
  const plan = CLINACT_PLANS[planKey];
  const referenceId = `clinact-${planKey}-${plan.amount_cents}`;

  const { plans } = await listPlans();
  const existing = plans?.find(
    (p) =>
      p.reference_id === referenceId &&
      p.status === "ACTIVE" &&
      p.amount?.value === plan.amount_cents &&
      p.interval?.unit === plan.interval,
  );
  if (existing) return existing.id;

  const created = await createPlan({
    reference_id: referenceId,
    name: `ClinAct ${plan.label}`,
    description: `Assinatura ${plan.label.toLowerCase()} do ClinAct`,
    amount_cents: plan.amount_cents,
    interval: { unit: plan.interval, length: plan.interval_count },
    audit,
  });
  return created.id;
}

/**
 * The PagBank coupon for a promotional offer, created on first use — same
 * pattern as ensurePlanId: the terms are in the reference AND re-checked
 * (couponMatches), so a changed offer can only ever create a new coupon.
 *
 * The list endpoint may omit `duration.occurrences`; a candidate whose
 * reference matches is then read individually before it is trusted.
 */
async function ensureCouponId(offer: PlanOffer, audit: ReturnType<typeof auditSink>): Promise<string> {
  const spec = couponSpec(offer);
  if (!spec) throw new Error("ensureCouponId called without a promotion");

  const { coupons } = await listCoupons({ reference_id: spec.reference_id });
  for (const listed of coupons ?? []) {
    if (listed.reference_id !== spec.reference_id) continue;
    if (couponMatches(listed, spec)) return listed.id;
    const full = await getCoupon(listed.id);
    if (couponMatches(full, spec)) return full.id;
  }

  const created = await createCoupon({ ...spec, audit });
  return created.id;
}

/** PagBank returns `next_invoice_at` as YYYY-MM-DD; fall back to one period. */
function paidUntilFrom(subscription: PagBankSubscription, planKey: ClinactPlanKey): string {
  if (subscription.next_invoice_at) {
    const parsed = new Date(`${subscription.next_invoice_at}T12:00:00-03:00`);
    if (!Number.isNaN(parsed.getTime())) return parsed.toISOString();
  }
  const fallback = new Date();
  if (planKey === "anual") fallback.setFullYear(fallback.getFullYear() + 1);
  else fallback.setMonth(fallback.getMonth() + 1);
  return fallback.toISOString();
}

/** The subscription's invoices, or none when PagBank could not be read (= not paid). */
async function invoicesOf(subscriptionId: string): Promise<PagBankInvoice[]> {
  try {
    const { invoices } = await listInvoices(subscriptionId);
    return invoices ?? [];
  } catch {
    return [];
  }
}

/**
 * Grants access. `paid_until` only ever moves FORWARD — the invariant from
 * schema-patch-clinact.sql — so a slow webhook arriving after a renewal can
 * never shorten what a student already paid for.
 */
export async function grantAccess(userId: string, paidUntil: string): Promise<void> {
  const admin = createAdminClient();
  const { data: current } = await admin
    .from("user_product_access")
    .select("paid_until")
    .eq("user_id", userId)
    .eq("product", "clinact")
    .maybeSingle();

  const furthest =
    current?.paid_until && new Date(current.paid_until) > new Date(paidUntil)
      ? current.paid_until
      : paidUntil;

  await admin.from("user_product_access").upsert(
    {
      user_id: userId,
      product: "clinact",
      source: "subscription",
      paid_until: furthest,
      updated_at: new Date().toISOString(),
    },
    { onConflict: "user_id,product" },
  );
}

async function recordSubscription(input: {
  userId: string;
  referenceId: string;
  subscription: PagBankSubscription | null;
  customerId: string | null;
  planKey: ClinactPlanKey;
  planId: string | null;
  /** What this subscription was sold at — the promotion, when there was one. */
  offer: PlanOffer;
  couponId: string | null;
  card?: { brand?: string; last?: string } | null;
  /** The cardholder typed at checkout — payment data, NOT the tomador. */
  billing: { name: string; taxId: string; phone: string };
  tomador: NfseTomador;
}): Promise<void> {
  const t = input.tomador;
  const admin = createAdminClient();
  await admin.from("clinact_subscriptions").upsert(
    {
      user_id: input.userId,
      reference_id: input.referenceId,
      pagbank_subscription_id: input.subscription?.id ?? null,
      pagbank_customer_id: input.customerId,
      plan_key: input.planKey,
      pagbank_plan_id: input.planId,
      // One row per user, overwritten by every new subscription: the offer is
      // ALWAYS written, so a re-subscription never inherits the previous one's
      // promotion. (The e-mail markers need no reset: they name the PagBank
      // subscription they were sent for — see subscription-emails.ts.)
      promotion_key: input.offer.promotion?.key ?? null,
      promo_amount_cents: input.offer.promotion ? input.offer.first_cents : null,
      promo_cycles: input.offer.promotion ? input.offer.promo_cycles : null,
      pagbank_coupon_id: input.couponId,
      status: input.subscription?.status ?? null,
      card_brand: input.card?.brand ?? null,
      card_last_digits: input.card?.last ?? null,
      billing_name: input.billing.name,
      billing_tax_id: input.billing.taxId,
      billing_phone: input.billing.phone,
      tomador_type: t.type,
      tomador_name: t.name,
      tomador_document: t.document,
      tomador_email: t.email,
      tomador_phone: t.phone,
      tomador_cep: t.cep,
      tomador_street: t.street,
      tomador_number: t.number,
      tomador_complement: t.complement || null,
      tomador_neighborhood: t.neighborhood,
      tomador_city: t.city,
      tomador_state: t.state,
      environment: getSubscriptionsEnv(),
      updated_at: new Date().toISOString(),
    },
    { onConflict: "user_id" },
  );
}

export async function subscribeToClinact(input: SubscribeInput): Promise<SubscribeResult> {
  const referenceId = `clinact-${input.planKey}-${input.attemptId}`.slice(0, 64);
  const audit = auditSink(input.userId, referenceId);
  const billing = {
    name: input.name,
    taxId: input.taxId,
    phone: `${input.phone.area}${input.phone.number}`,
  };

  // What is charged is decided HERE, on the Brazilian date of the charge — the
  // same planOffer() every screen uses. If the checkout showed a different
  // first charge (the promotion ended while the page was open), stop before
  // anything reaches PagBank: the student confirms the price they will pay.
  const offer = planOffer(input.planKey, todayKeyBR());
  if (input.expectedFirstCents !== undefined && input.expectedFirstCents !== offer.first_cents) {
    return {
      ok: false,
      priceChanged: true,
      error: offer.promotion
        ? "As condições deste plano mudaram. Atualize a página para ver o valor atual — nenhuma cobrança foi feita."
        : "A Condição de lançamento Black Friday terminou. Atualize a página para ver o valor atual — nenhuma cobrança foi feita.",
    };
  }

  let planId: string;
  let couponId: string | null = null;
  try {
    planId = await ensurePlanId(input.planKey, audit);
    // No coupon → no promotional charge. Never fall back to the full price for
    // a student who was shown the promotional one: refuse, charge nothing.
    if (offer.promotion) couponId = await ensureCouponId(offer, audit);
  } catch {
    return { ok: false, error: GENERIC_ERROR };
  }

  // ── The subscriber, with the card encrypted in their browser ──────────────
  //
  // NOT always a create. PagBank refuses a second customer with the same CPF,
  // so a student who cancelled and came back would be told their own CPF is
  // already registered and could never subscribe again. Three ways in, in order
  // of certainty:
  //
  //   1. the customer id we already stored for this user;
  //   2. a create, for a genuinely new subscriber;
  //   3. on 409, a lookup by CPF — someone else's row, an old test, a deleted
  //      local record: the customer exists at PagBank and must be found.
  //
  // Reusing a customer means the card they just typed has to replace the one on
  // file, which is what setCustomerCard does — and it returns the new token.
  let customerId: string | null = null;
  let cardToken: string | null = null;
  let card: { brand?: string; last?: string } | null = null;

  const admin = createAdminClient();
  const { data: existing } = await admin
    .from("clinact_subscriptions")
    .select("pagbank_customer_id")
    .eq("user_id", input.userId)
    .maybeSingle();
  if (existing?.pagbank_customer_id) customerId = existing.pagbank_customer_id as string;

  try {
    if (!customerId) {
      try {
        const created = await createCustomer({
          reference_id: customerReference(input.userId),
          name: input.name,
          email: input.email,
          tax_id: input.taxId,
          phone: input.phone,
          encrypted_card: input.encryptedCard,
          // The CPF is part of the key: PagBank replays the FIRST answer for a
          // reused key (a 409 "CPF already registered" included), so a student
          // who corrects a mistyped CPF would otherwise be refused until they
          // reloaded the page. Same CPF = same key = still a safe retry.
          idempotency_key: key(input.attemptId, "cust", input.taxId),
          audit,
        });
        customerId = created.id;
        cardToken = customerCardToken(created);
        const registered = created.billing_info?.[0]?.card;
        card = registered ? { brand: registered.brand, last: registered.last_digits } : null;
      } catch (err) {
        // 409 means the CPF already belongs to a subscriber. Finding them is
        // NOT permission to use them.
        //
        // A CPF is not a secret in Brazil. If a found customer were reused on
        // the strength of the CPF alone, anyone could type someone else's
        // number and we would overwrite that person's card on file with the
        // attacker's — their renewals would then charge a stranger's card, and
        // the attacker's subscription would hang off the victim's record.
        //
        // So the customer is only reused when PagBank's own record says it is
        // this user's: we write the subscriber reference as clinact-user-<id>,
        // and that is what gets checked here. Anything else — an older
        // customer, a test, a genuine duplicate CPF — stops and goes to
        // support, where a human can verify identity.
        if (!(err instanceof PagBankSubscriptionsError && err.status === 409)) throw err;
        const { customers } = await findCustomersByDocument(input.taxId);
        const owned = (customers ?? []).find(
          (c) => c.reference_id === customerReference(input.userId),
        );
        if (!owned) return { ok: false, error: DUPLICATE_CUSTOMER_ERROR };
        customerId = owned.id;
      }
    }

    // Reused customer (stored or found): put the card they just typed on file.
    if (customerId && !cardToken) {
      const updated = await setCustomerCard(customerId, input.encryptedCard, audit);
      cardToken = customerCardToken(updated);
      const registered = updated.billing_info?.[0]?.card;
      card = registered ? { brand: registered.brand, last: registered.last_digits } : null;
    }
  } catch {
    return { ok: false, error: GENERIC_ERROR };
  }

  if (!customerId) return { ok: false, error: GENERIC_ERROR };
  if (!cardToken) return { ok: false, error: GENERIC_ERROR };

  // ── The subscription. This is the call that charges. ──────────────────────
  let subscription: PagBankSubscription | null = null;
  try {
    subscription = await createSubscription({
      reference_id: referenceId,
      plan_id: planId,
      customer_id: customerId,
      card_token: cardToken,
      security_code: input.securityCode,
      coupon_id: couponId ?? undefined,
      idempotency_key: key(input.attemptId, "sub"),
      audit,
    });
  } catch (err) {
    // A replayed key means the first attempt may already have gone through.
    // Look it up — never charge again to find out.
    if (isIdempotencyConflict(err)) {
      const outcome = await reconcileByReference(referenceId);
      if (outcome.kind === "paid") {
        const found = await findSubscriptionByReference(referenceId);
        if (found) {
          await recordSubscription({ userId: input.userId, referenceId, subscription: found, customerId, planKey: input.planKey, planId, offer, couponId, card, billing, tomador: input.tomador });
          await grantAccess(input.userId, paidUntilFrom(found, input.planKey));
          await recordPaidInvoicesFor(input.userId, found.id);
          await sendSubscriptionConfirmation(input.userId);
          return { ok: true, state: "paid", subscriptionId: outcome.subscriptionId, paidUntil: paidUntilFrom(found, input.planKey) };
        }
      }
      if (outcome.kind === "pending") {
        return { ok: true, state: "pending", subscriptionId: outcome.subscriptionId };
      }
    }
    await recordSubscription({ userId: input.userId, referenceId, subscription: null, customerId, planKey: input.planKey, planId, offer, couponId, card, billing, tomador: input.tomador });
    return { ok: false, error: GENERIC_ERROR };
  }

  await recordSubscription({ userId: input.userId, referenceId, subscription, customerId, planKey: input.planKey, planId, offer, couponId, card, billing, tomador: input.tomador });

  // 201 does NOT mean paid. Ask the invoice.
  const invoices = await invoicesOf(subscription.id);
  const paid = invoices.some((i) => i.status === "PAID");
  if (!paid) {
    // OVERDUE at creation means the issuer declined the first charge.
    if (subscription.status === "OVERDUE" || subscription.status === "PENDING_ACTION") {
      return { ok: false, error: DECLINED_ERROR };
    }
    return { ok: true, state: "pending", subscriptionId: subscription.id };
  }

  const paidUntil = paidUntilFrom(subscription, input.planKey);
  await grantAccess(input.userId, paidUntil);
  // The paid invoice gets its NFS-e row. After access; swallows its own failures.
  await recordPaidInvoices(input.userId, subscription.id, invoices);

  // The student was shown first_cents. If PagBank charged anything else (a
  // coupon it ignored), that is a promise broken — nothing here can undo a
  // charge, so make it loud for a human on /admin/erros.
  const charged = invoices.find((i) => i.status === "PAID")?.amount?.value;
  if (charged !== undefined && charged !== offer.first_cents) {
    await recordAppError({
      kind: "server",
      message: `ClinAct: primeira cobrança de ${charged} centavos, mas o aluno viu ${offer.first_cents} (assinatura ${subscription.id}, plano ${input.planKey}, cupom ${couponId ?? "nenhum"})`,
      route: "/api/clinact/assinar",
      digest: null,
      stack: null,
      path: null,
      userAgent: null,
    });
  }

  await sendSubscriptionConfirmation(input.userId);
  return { ok: true, state: "paid", subscriptionId: subscription.id, paidUntil };
}

